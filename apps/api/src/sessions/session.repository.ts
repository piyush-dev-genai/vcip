/**
 * Session persistence.
 *
 * PostgreSQL is authoritative for session state (D1, invariant I1). Every
 * mutation here is a **guarded** update: the caller says which status and
 * version it observed, and the UPDATE only commits if the row still looks that
 * way. Zero affected rows means someone else moved the session first, and the
 * caller turns that into a `409`.
 *
 * That is the single-winner pattern D5 and D17 specify, applied to the customer
 * side of the lifecycle. It is not optimistic locking bolted on for tidiness:
 * a customer pressing "abort" while an agent submits a verdict is a real race,
 * and only one of them may commit.
 *
 * Each mutation writes its `session_events` row **inside the same transaction**
 * as the update. A status change with no event, or an event for a change that
 * did not commit, would both be lies in the audit trail.
 *
 * Port plus adapter, as with `ApiKeyStore` (T09) and `TenantConfigStore`: the
 * service depends on the interface, so the lifecycle rules are testable without
 * a database, and the SQL lives in exactly one file.
 */

import { Inject, Injectable } from '@nestjs/common';
import type { SessionEventType, SessionStatus } from '@vcip/shared';
import { and, eq, sql } from 'drizzle-orm';
import type { PostgresJsDatabase } from 'drizzle-orm/postgres-js';
import { sessions } from '../../db/schema.js';
import { InjectDatabase } from '../common/db/db.tokens.js';
import type { EventActorType, EventPayload, SessionEventWriter } from '../common/events/index.js';
import { InjectSessionEventWriter } from '../common/events/index.js';

// Re-exported, not redefined: T13 moved the actor union to the event writer,
// where it is derived from the schema's own ACTOR_TYPES rather than retyped.
export type { EventActorType };

/**
 * A session row, as the API reads it.
 *
 * Deliberately not every column. Queue, offer, verdict, and billing columns are
 * owned by later tasks; including them here would invite this module to start
 * writing them. `verdict` and the queue timestamps are present because
 * `GET /v1/sessions/:id` reports them.
 */
export interface SessionRow {
  readonly id: string;
  readonly tenantId: string;
  readonly externalRef: string;
  readonly status: SessionStatus;
  readonly version: number;
  readonly language: string;
  readonly roomName: string | null;
  readonly checklistTemplateId: string | null;

  readonly consentOk: boolean;
  readonly consentVersion: string | null;
  readonly consentAt: Date | null;

  readonly preflightOk: boolean;
  readonly preflightAt: Date | null;

  readonly geoOk: boolean;
  readonly gpsAccuracyM: number | null;
  readonly geoCheckedAt: Date | null;
  readonly ipCountry: string | null;

  readonly queuedAt: Date | null;
  readonly connectedAt: Date | null;
  readonly endedAt: Date | null;

  readonly verdict: string | null;
  readonly exportStatus: string;

  readonly createdAt: Date;
  readonly updatedAt: Date;
}

/**
 * An event to append alongside a mutation.
 *
 * The tenant and session are absent because the repository already knows them —
 * they come from the mutation being performed, never from the event, so the two
 * cannot disagree.
 *
 * `payload` is `EventPayload`, which is a JSON type rather than
 * `Record<string, unknown>`: the column is JSONB, and a value that cannot
 * survive serialisation should fail to compile rather than serialise to `null`.
 * Which keys are permitted is the writer's boundary (T13), not this file's.
 */
export interface SessionEventInput {
  readonly type: SessionEventType;
  readonly actorType: EventActorType;
  readonly actorId: string | null;
  readonly payload: EventPayload;
}

export interface CreateSessionInput {
  /** Generated by the caller, because `room_name` is derived from it (R2). */
  readonly id: string;
  readonly tenantId: string;
  readonly externalRef: string;
  readonly language: string;
  readonly roomName: string;
  readonly checklistTemplateId: string | null;
  readonly event: SessionEventInput;
}

/**
 * Columns a customer-lifecycle mutation may set.
 *
 * Everything absent from this list is unreachable from T12 by construction:
 * no `verdict`, no `agent_id`, no `bill_amount_paise`, no `export_status`.
 */
export interface SessionMutation {
  readonly status?: SessionStatus;
  readonly consentOk?: boolean;
  readonly consentVersion?: string;
  readonly consentAt?: Date;
  readonly preflightOk?: boolean;
  readonly preflightAt?: Date;
  readonly geoOk?: boolean;
  readonly gpsAccuracyM?: number;
  readonly geoCheckedAt?: Date;
  readonly ipCountry?: string | null;
  /**
   * Set once, on `CREATED -> QUEUED` (T15).
   *
   * Authoritative for queue ordering: the Redis ZSET score is this value, so a
   * retry or a reconciliation minutes later restores the customer's original
   * place rather than sending them to the back. Nothing rewrites it.
   */
  readonly queuedAt?: Date;
  readonly endedAt?: Date;
}

export interface GuardedUpdate {
  readonly sessionId: string;
  /** From the credential. Present in every WHERE clause (invariant I8). */
  readonly tenantId: string;
  /** The status the caller validated its decision against. */
  readonly expectedStatus: SessionStatus;
  /** The version the caller read. Together these make the update single-winner. */
  readonly expectedVersion: number;
  readonly set: SessionMutation;
  readonly event: SessionEventInput;
}

export interface SessionRepository {
  /** Insert the session and its `SESSION_CREATED` event in one transaction. */
  create(input: CreateSessionInput): Promise<SessionRow>;

  /**
   * Load a session by id, without a tenant filter.
   *
   * The tenant check is `TenantScope.assertOwnership` on the returned row, and
   * it must stay there: it answers "missing" and "another tenant's" with the
   * same 404, so an id cannot be probed for existence across tenants.
   */
  findById(sessionId: string): Promise<SessionRow | null>;

  /**
   * Apply a guarded mutation and append its event, atomically.
   *
   * Returns the updated row, or `null` when the guard matched no row — the
   * session moved, and the caller lost the race.
   */
  update(command: GuardedUpdate): Promise<SessionRow | null>;
}

export const SESSION_REPOSITORY = Symbol('SESSION_REPOSITORY');

export const InjectSessionRepository = (): ParameterDecorator => Inject(SESSION_REPOSITORY);

/** The columns every read returns, so the projection is defined once. */
const SESSION_COLUMNS = {
  id: sessions.id,
  tenantId: sessions.tenantId,
  externalRef: sessions.externalRef,
  status: sessions.status,
  version: sessions.version,
  language: sessions.language,
  roomName: sessions.roomName,
  checklistTemplateId: sessions.checklistTemplateId,
  consentOk: sessions.consentOk,
  consentVersion: sessions.consentVersion,
  consentAt: sessions.consentAt,
  preflightOk: sessions.preflightOk,
  preflightAt: sessions.preflightAt,
  geoOk: sessions.geoOk,
  gpsAccuracyM: sessions.gpsAccuracyM,
  geoCheckedAt: sessions.geoCheckedAt,
  ipCountry: sessions.ipCountry,
  queuedAt: sessions.queuedAt,
  connectedAt: sessions.connectedAt,
  endedAt: sessions.endedAt,
  verdict: sessions.verdict,
  exportStatus: sessions.exportStatus,
  createdAt: sessions.createdAt,
  updatedAt: sessions.updatedAt,
} as const;

type SelectedSession = {
  [K in keyof typeof SESSION_COLUMNS]: unknown;
};

const toRow = (row: SelectedSession): SessionRow => row as unknown as SessionRow;

@Injectable()
export class DrizzleSessionRepository implements SessionRepository {
  constructor(
    @InjectDatabase() private readonly db: PostgresJsDatabase,
    // T13's shared writer. It is handed this method's transaction, so the
    // session write and its event still commit or roll back together — the
    // property the inline inserts used to provide, now provided in one place.
    @InjectSessionEventWriter() private readonly events: SessionEventWriter,
  ) {}

  async create(input: CreateSessionInput): Promise<SessionRow> {
    return this.db.transaction(async (tx) => {
      const inserted = await tx
        .insert(sessions)
        .values({
          id: input.id,
          tenantId: input.tenantId,
          externalRef: input.externalRef,
          status: 'CREATED',
          language: input.language,
          roomName: input.roomName,
          checklistTemplateId: input.checklistTemplateId,
          // Stated rather than left to the column default, because the two
          // status axes starting independently is the point of D3.
          exportStatus: 'NOT_STARTED',
        })
        .returning(SESSION_COLUMNS);

      const row = inserted[0];
      /* c8 ignore next */
      if (row === undefined) throw new Error('session insert returned no row');

      // The session was inserted a moment ago in this same transaction, so the
      // writer's `WHERE EXISTS` ownership check sees it.
      await this.events.append(
        {
          tenantId: input.tenantId,
          sessionId: input.id,
          eventType: input.event.type,
          actorType: input.event.actorType,
          actorId: input.event.actorId,
          payload: input.event.payload,
        },
        tx,
      );

      return toRow(row);
    });
  }

  async findById(sessionId: string): Promise<SessionRow | null> {
    const rows = await this.db
      .select(SESSION_COLUMNS)
      .from(sessions)
      .where(eq(sessions.id, sessionId))
      .limit(1);

    const row = rows[0];
    return row === undefined ? null : toRow(row);
  }

  async update(command: GuardedUpdate): Promise<SessionRow | null> {
    return this.db.transaction(async (tx) => {
      const updated = await tx
        .update(sessions)
        .set({
          ...command.set,
          // Always bumped, so a concurrent reader's guard fails even when the
          // status did not change (a consent write, for instance).
          version: sql`${sessions.version} + 1`,
          updatedAt: new Date(),
        })
        .where(
          and(
            eq(sessions.id, command.sessionId),
            // Tenant is in the WHERE clause, not just checked beforehand: the
            // guard is the thing that actually runs against the row.
            eq(sessions.tenantId, command.tenantId),
            eq(sessions.status, command.expectedStatus),
            eq(sessions.version, command.expectedVersion),
          ),
        )
        .returning(SESSION_COLUMNS);

      const row = updated[0];
      // Zero rows: the session moved between the read and the write. Return
      // null and roll back, so no event is appended for a change that did not
      // happen.
      if (row === undefined) return null;

      await this.events.append(
        {
          tenantId: command.tenantId,
          sessionId: command.sessionId,
          eventType: command.event.type,
          actorType: command.event.actorType,
          actorId: command.event.actorId,
          payload: command.event.payload,
        },
        tx,
      );

      return toRow(row);
    });
  }
}
