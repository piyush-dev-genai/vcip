export interface SessionRepository {
  /** Insert the session and its `SESSION_CREATED` event in one transaction. */
  create(input: CreateSessionInput): Promise<SessionRow>;

  /**
   * Load a session by id, without a tenant filter.
   *
   * The tenant check is `TenantScope.assertOwnership` on the returned row, and
   * it must stay there: it answers "missing" and "another tenant's" with the
   * same 404, so an id cannot be probed for existence across tenants.
   */
  findById(sessionId: string): Promise<SessionRow | null>;

  /**
   * Apply a guarded mutation and append its event, atomically.
   *
   * Returns the updated row, or `null` when the guard matched no row — the
   * session moved, and the caller lost the race.
   */
  update(command: GuardedUpdate): Promise<SessionRow | null>;

  /**
   * The subset of `sessionIds` that this tenant currently has `QUEUED`.
   *
   * One statement for the whole candidate set — the alternative, a lookup per
   * Redis member, is an N+1 on a request path. The tenant predicate and the
   * status predicate are both in the WHERE clause rather than applied to the
   * result, so a stale Redis member or another tenant's id cannot come back at
   * all; there is no row to forget to filter.
   *
   * Order is not specified. Redis owns the ordering, and the caller re-applies
   * it — a database `ORDER BY` here would quietly become a second answer to a
   * question the queue projection already answers.
   */
  findQueued(tenantId: string, sessionIds: readonly string[]): Promise<readonly QueuedSessionRow[]>;

  /**
   * Claim a queued session for an agent: `QUEUED -> OFFERED` (D4, D5).
   *
   * The whole operation is one transaction, and the order inside it matters:
   * the agent is serialised first, then counted, then the session is taken.
   * See the implementation for why the count alone would not hold.
   *
   * This is the single-winner guard for the offer. Redis `BUSY` is not — a
   * presence key can expire mid-claim, and D1 makes PostgreSQL authoritative
   * for business state regardless.
   */
  claim(command: ClaimCommand): Promise<SessionClaimOutcome>;

  /**
   * One session, as the claim path needs to see it.
   *
   * Tenant-scoped in SQL rather than fetched and then checked, so another
   * tenant's row is never loaded at all (I8) — the same treatment `findQueued`
   * gets, and a narrowing on `findById`, which returns every column of any
   * session by id.
   */
  findClaimable(tenantId: string, sessionId: string): Promise<ClaimableSessionRow | null>;

  /**
   * One session, as the media-token path needs to see it (T24, contract §13).
   *
   * Tenant-scoped in SQL for the reason `findClaimable` is: another tenant's
   * row is never loaded, so the 404 it produces is a property of the query
   * rather than of a check someone has to remember to write.
   *
   * A separate read rather than `findById`, because the two answer different
   * questions. `findById` returns every column of any session by id and is
   * right for the polling view; this returns the five a token decision is made
   * from, and returning fewer columns is the point.
   */
  findForMediaToken(tenantId: string, sessionId: string): Promise<MediaTokenSessionRow | null>;

  /**
   * Take up an offer: `OFFERED -> IN_CALL` (T19, §17.2).
   *
   * Single-winner in the same way the claim is, and against a wider field: the
   * other contender is not another agent but the expiry sweeper, which is
   * trying to move the same row back to `QUEUED`.
   */
  accept(command: AcceptCommand): Promise<SessionAcceptOutcome>;

  /**
   * How many sessions this agent is currently holding.
   *
   * The same definition the claim counts against, exposed as a read so the
   * availability endpoint can refuse to advertise a busy agent as free. It is
   * asked of PostgreSQL rather than of the presence key, because the presence
   * key is exactly the thing being decided and D1 puts the authority in the
   * database.
   */
  countActiveWork(tenantId: string, agentId: string): Promise<number>;

  /**
   * The sessions this agent is currently holding, oldest first.
   *
   * The same definition `countActiveWork` counts and the claim's capacity check
   * uses — one predicate, so "how many do I hold" and "which ones" can never
   * disagree. A list rather than one row because `agent_profiles.max_concurrent`
   * may exceed one; the portal is single-session and takes the first, and
   * saying so honestly is better than a signature that pretends there can only
   * ever be one.
   */
  findActiveWork(tenantId: string, agentId: string): Promise<readonly AgentWorkRow[]>;

  /**
   * One session, for a LiveKit webhook (T26).
   *
   * Not tenant-scoped, because the caller has no tenant to scope by. See
   * `CallSessionRow`.
   */
  findForCallEvent(sessionId: string): Promise<CallSessionRow | null>;

  /**
   * Append an event to a session without moving it (T26).
   *
   * `CALL_STARTED`, `AGENT_DISCONNECTED` and `AGENT_RECONNECTED` are facts about
   * a call that change no status: D18 is explicit that a disconnected agent
   * keeps the session, and D25 keeps that history in events rather than in a
   * column. `update()` cannot express this — it exists to move a session and
   * takes an expected status to guard the move.
   *
   * Returns false when the session does not exist. Appending is otherwise
   * unconditional: an append-only log (I10) has nothing to race against.
   */
  appendCallEvent(sessionId: string, event: SessionEventInput): Promise<boolean>;

  /**
   * Has this event type ever been appended to this session?
   *
   * The once-only guard for `CALL_STARTED`. PostgreSQL answers it rather than
   * Redis, because "did this call ever start" is durable history and Redis
   * holds only the transient room presence that led to the question (D1/D2).
   */
  hasEvent(sessionId: string, eventType: SessionEventType): Promise<boolean>;

  /**
   * End a call with no verdict: `IN_CALL -> DROPPED_IN_CALL | ABORTED` (T26).
   *
   * Guarded on `status = 'IN_CALL'`, so a verdict that committed first (T35), a
   * customer abort, or a second sweeper pass all match nothing and get `null`.
   * The billing row and the event are written in the same transaction.
   */
  endCall(command: EndCallCommand): Promise<EndedCallRow | null>;

  /**
   * The verdict transaction (T35, schema §45).
   *
   * The most important write in the system, and the reason it is one statement
   * list rather than several calls: §46 spells out the two states nobody wants
   * — a session `APPROVED` with no billing row, and a billing row for a session
   * that never reached a verdict. Both are impossible only if the transition,
   * the charge, the attestation, the AI snapshot, the history and the outbox
   * commit together.
   *
   * Single-winner (D17). The guarded UPDATE demands `IN_CALL`, this tenant,
   * this agent, and `verdict IS NULL`; a customer disconnect that got there
   * first leaves the row somewhere else and this matches nothing, reporting
   * `LOST` rather than overwriting a terminal outcome (I11).
   */
  submitVerdict(command: SubmitVerdictCommand): Promise<SubmitVerdictOutcome>;

  /**
   * Calls that are under way with no recording running (T28).
   *
   * Cross-tenant, like the offer sweeper's read and for the same reason: a
   * recovery pass has no caller and acts as the system, so there is no
   * authenticated tenant to scope it by.
   *
   * Bounded by `limit`, so one pass costs the batch rather than however many
   * recordings failed while the egress container was down.
   */
  findUnrecordedCalls(limit: number): Promise<readonly UnrecordedCallRow[]>;

  /**
   * Return lapsed offers to the queue: `OFFERED -> QUEUED` (T20, §17.3).
   *
   * Cross-tenant, and the one read in this file that is. A sweeper exists to
   * find work nobody is asking for, so there is no authenticated tenant to
   * scope it by — it runs as the system, not on behalf of a caller, which is
   * why it is unreachable from any route.
   *
   * Bounded by `limit`, so one pass is proportional to the batch rather than to
   * however many offers lapsed while the process was down.
   */
  expireOffers(command: ExpireOffersCommand): Promise<readonly ExpiredOfferRow[]>;
}

export const SESSION_REPOSITORY = Symbol('SESSION_REPOSITORY');

export const InjectSessionRepository = (): ParameterDecorator => Inject(SESSION_REPOSITORY);

/**
 * What counts as an agent holding work.
 *
 * One definition, used by the claim's capacity check and by the availability
 * guard, because two copies of this predicate that drifted apart would mean an
 * agent could be refused a claim for being at capacity while simultaneously
 * being allowed to advertise themselves as free.
 *
 * Both halves of "holding": an offer not yet accepted, keyed by
 * `offered_to_agent_id`, and a call in progress, keyed by `agent_id`. Each id
 * is paired with its status, so the offer columns left behind as history on an
 * `IN_CALL` row (§17.2) cannot be counted twice, and a stale
 * `offered_to_agent_id` on a session that has moved on counts for nothing.
 */
const holdsActiveWork = (tenantId: string, agentId: string) =>
  and(
    eq(sessions.tenantId, tenantId),
    or(
      and(eq(sessions.status, SessionStatus.OFFERED), eq(sessions.offeredToAgentId, agentId)),
      and(eq(sessions.status, SessionStatus.IN_CALL), eq(sessions.agentId, agentId)),
    ),
  );

/** The columns every read returns, so the projection is defined once. */
const SESSION_COLUMNS = {
  id: sessions.id,
  tenantId: sessions.tenantId,
  externalRef: sessions.externalRef,
  status: sessions.status,
  version: sessions.version,
  language: sessions.language,
  roomName: sessions.roomName,
  checklistTemplateId: sessions.checklistTemplateId,
  consentOk: sessions.consentOk,
  consentVersion: sessions.consentVersion,
  consentAt: sessions.consentAt,
  preflightOk: sessions.preflightOk,
  preflightAt: sessions.preflightAt,
  geoOk: sessions.geoOk,
  gpsAccuracyM: sessions.gpsAccuracyM,
  geoCheckedAt: sessions.geoCheckedAt,
  ipCountry: sessions.ipCountry,
  queuedAt: sessions.queuedAt,
  connectedAt: sessions.connectedAt,
  endedAt: sessions.endedAt,
  verdict: sessions.verdict,
  exportStatus: sessions.exportStatus,
  createdAt: sessions.createdAt,
  updatedAt: sessions.updatedAt,
} as const;

type SelectedSession = {
  [K in keyof typeof SESSION_COLUMNS]: unknown;
};

const toRow = (row: SelectedSession): SessionRow => row as unknown as SessionRow;

@Injectable()
export class DrizzleSessionRepository implements SessionRepository {
  constructor(
    @InjectDatabase() private readonly db: PostgresJsDatabase,
    // T13's shared writer. It is handed this method's transaction, so the
    // session write and its event still commit or roll back together — the
    // property the inline inserts used to provide, now provided in one place.
    @InjectSessionEventWriter() private readonly events: SessionEventWriter,
  ) {}

  async create(input: CreateSessionInput): Promise<SessionRow> {
    return this.db.transaction(async (tx) => {
      const inserted = await tx
        .insert(sessions)
        .values({
          id: input.id,
          tenantId: input.tenantId,
          externalRef: input.externalRef,
          status: 'CREATED',
          language: input.language,
          roomName: input.roomName,
          checklistTemplateId: input.checklistTemplateId,
          // Stated rather than left to the column default, because the two
          // status axes starting independently is the point of D3.
          exportStatus: 'NOT_STARTED',
        })
        .returning(SESSION_COLUMNS);

      const row = inserted[0];
      /* c8 ignore next */
      if (row === undefined) throw new Error('session insert returned no row');

      // The session was inserted a moment ago in this same transaction, so the
      // writer's `WHERE EXISTS` ownership check sees it.
      await this.events.append(
        {
          tenantId: input.tenantId,
          sessionId: input.id,
          eventType: input.event.type,
          actorType: input.event.actorType,
          actorId: input.event.actorId,
          payload: input.event.payload,
        },
        tx,
      );

      return toRow(row);
    });
  }

  async findById(sessionId: string): Promise<SessionRow | null> {
    const rows = await this.db
      .select(SESSION_COLUMNS)
      .from(sessions)
      .where(eq(sessions.id, sessionId))
      .limit(1);

    const row = rows[0];
    return row === undefined ? null : toRow(row);
  }

  async findQueued(
    tenantId: string,
    sessionIds: readonly string[],
  ): Promise<readonly QueuedSessionRow[]> {
    // No ids means no query. `inArray` with an empty list is a SQL degenerate
    // case worth never generating.
    if (sessionIds.length === 0) return [];

    const rows = await this.db
      .select({
        id: sessions.id,
        language: sessions.language,
        priority: sessions.priority,
        queuedAt: sessions.queuedAt,
      })
      .from(sessions)
      .where(
        and(
          // Tenant first, and in SQL: invariant I8 holds because the row is
          // never fetched, not because a later check rejects it.
          eq(sessions.tenantId, tenantId),
          // A positive test on one status. Every other status — OFFERED,
          // DROPPED_QUEUED, and the seven others — is excluded by not being
          // named, so a status added later cannot leak in by omission.
          eq(sessions.status, SessionStatus.QUEUED),
          inArray(sessions.id, [...sessionIds]),
          isNotNull(sessions.queuedAt),
        ),
      );

    return rows.map((row) => ({
      id: row.id,
      language: row.language,
      priority: row.priority,
      /* c8 ignore next -- isNotNull already proved this */
      queuedAt: row.queuedAt ?? new Date(0),
    }));
  }

  async update(command: GuardedUpdate): Promise<SessionRow | null> {
    return this.db.transaction(async (tx) => {
      const updated = await tx
        .update(sessions)
        .set({
          ...command.set,
          // Always bumped, so a concurrent reader's guard fails even when the
          // status did not change (a consent write, for instance).
          version: sql`${sessions.version} + 1`,
          updatedAt: new Date(),
        })
        .where(
          and(
            eq(sessions.id, command.sessionId),
            // Tenant is in the WHERE clause, not just checked beforehand: the
            // guard is the thing that actually runs against the row.
            eq(sessions.tenantId, command.tenantId),
            eq(sessions.status, command.expectedStatus),
            eq(sessions.version, command.expectedVersion),
          ),
        )
        .returning(SESSION_COLUMNS);

      const row = updated[0];
      // Zero rows: the session moved between the read and the write. Return
      // null and roll back, so no event is appended for a change that did not
      // happen.
      if (row === undefined) return null;

      await this.events.append(
        {
          tenantId: command.tenantId,
          sessionId: command.sessionId,
          eventType: command.event.type,
          actorType: command.event.actorType,
          actorId: command.event.actorId,
          payload: command.event.payload,
        },
        tx,
      );

      return toRow(row);
    });
  }

  async findClaimable(tenantId: string, sessionId: string): Promise<ClaimableSessionRow | null> {
    const rows = await this.db
      .select({
        id: sessions.id,
        tenantId: sessions.tenantId,
        status: sessions.status,
        language: sessions.language,
        offeredToAgentId: sessions.offeredToAgentId,
        offeredAt: sessions.offeredAt,
        offerExpiresAt: sessions.offerExpiresAt,
      })
      .from(sessions)
      // Both predicates in the WHERE clause: a foreign id yields no row rather
      // than a row a later check has to remember to reject.
      .where(and(eq(sessions.id, sessionId), eq(sessions.tenantId, tenantId)))
      .limit(1);

    const row = rows[0];
    if (row === undefined) return null;
    return { ...row, status: row.status as SessionStatus };
  }

  async findForMediaToken(
    tenantId: string,
    sessionId: string,
  ): Promise<MediaTokenSessionRow | null> {
    const rows = await this.db
      .select({
        id: sessions.id,
        tenantId: sessions.tenantId,
        status: sessions.status,
        roomName: sessions.roomName,
        agentId: sessions.agentId,
      })
      .from(sessions)
      // Both predicates in the WHERE clause, as `findClaimable` does it: a
      // foreign id yields no row rather than a row a later check has to
      // remember to reject (I8).
      .where(and(eq(sessions.id, sessionId), eq(sessions.tenantId, tenantId)))
      .limit(1);

    const row = rows[0];
    if (row === undefined) return null;
    return { ...row, status: row.status as SessionStatus };
  }

  async countActiveWork(tenantId: string, agentId: string): Promise<number> {
    const [row] = await this.db
      .select({ active: sql<string>`count(*)` })
      .from(sessions)
      .where(holdsActiveWork(tenantId, agentId));
    return Number(row?.active ?? 0);
  }

  async findActiveWork(tenantId: string, agentId: string): Promise<readonly AgentWorkRow[]> {
    const rows = await this.db
      .select({
        id: sessions.id,
        tenantId: sessions.tenantId,
        status: sessions.status,
        roomName: sessions.roomName,
        offerExpiresAt: sessions.offerExpiresAt,
        // When the session became this agent's: the accept for a call, the
        // claim for an outstanding offer. Coalesced so one column orders both.
        heldSince: sql<Date>`coalesce(${sessions.connectedAt}, ${sessions.offeredAt}, ${sessions.updatedAt})`,
      })
      .from(sessions)
      // The same predicate the capacity count and the claim use.
      .where(holdsActiveWork(tenantId, agentId))
      .orderBy(sessions.createdAt);

    return rows.map((row) => ({
      ...row,
      status: row.status as SessionStatus,
      heldSince: new Date(row.heldSince as unknown as string),
    }));
  }

  async findForCallEvent(sessionId: string): Promise<CallSessionRow | null> {
    // `call_started_at` is a correlated subquery rather than a join, so a
    // session with no CALL_STARTED yet still comes back — with null — instead
    // of vanishing from the result.
    const rows = await this.db.execute<{
      id: string;
      tenant_id: string;
      status: string;
      room_name: string | null;
      agent_id: string | null;
      queued_at: Date | null;
      connected_at: Date | null;
      call_started_at: Date | null;
    }>(sql`
      SELECT s.id,
             s.tenant_id,
             s.status,
             s.room_name,
             s.agent_id,
             s.queued_at,
             s.connected_at,
             (SELECT min(e.server_ts)
                FROM session_events e
               WHERE e.session_id = s.id
                 AND e.event_type = ${SessionEventType.CALL_STARTED}::text) AS call_started_at
        FROM sessions s
       WHERE s.id = ${sessionId}::uuid
    `);

    const row = rows[0];
    if (row === undefined) return null;
    return {
      id: row.id,
      tenantId: row.tenant_id,
      status: row.status as SessionStatus,
      roomName: row.room_name,
      agentId: row.agent_id,
      queuedAt: row.queued_at === null ? null : new Date(row.queued_at),
      connectedAt: row.connected_at === null ? null : new Date(row.connected_at),
      callStartedAt: row.call_started_at === null ? null : new Date(row.call_started_at),
    };
  }

  async appendCallEvent(sessionId: string, event: SessionEventInput): Promise<boolean> {
    const [row] = await this.db
      .select({ id: sessions.id, tenantId: sessions.tenantId })
      .from(sessions)
      .where(eq(sessions.id, sessionId))
      .limit(1);
    if (row === undefined) return false;

    await this.events.append(
      {
        sessionId: row.id,
        tenantId: row.tenantId,
        eventType: event.type,
        actorType: event.actorType,
        actorId: event.actorId,
        payload: event.payload,
      },
      this.db,
    );
    return true;
  }

  async hasEvent(sessionId: string, eventType: SessionEventType): Promise<boolean> {
    const rows = await this.db.execute<{ present: boolean }>(sql`
      SELECT EXISTS (
        SELECT 1 FROM session_events
         WHERE session_id = ${sessionId}::uuid
           AND event_type = ${eventType}::text
      ) AS present
    `);
    return rows[0]?.present === true;
  }

  async endCall(command: EndCallCommand): Promise<EndedCallRow | null> {
    return this.db.transaction(async (tx) => {
      // Guarded on IN_CALL. A verdict (T35), a customer abort, or a second
      // sweeper pass all leave the session somewhere else, and this matches
      // nothing rather than overwriting a terminal status (I11).
      const [updated] = await tx
        .update(sessions)
        .set({
          status: command.status,
          endedAt: command.now,
          // Measured from CALL_STARTED — the instant both participants were in
          // the room — not from the accept. A call nobody both-joined has no
          // talk time, and null says so rather than a fabricated zero.
          talkMs: sql`CASE WHEN (
            SELECT min(e.server_ts) FROM session_events e
             WHERE e.session_id = ${command.sessionId}::uuid
               AND e.event_type = ${SessionEventType.CALL_STARTED}::text
          ) IS NULL THEN NULL ELSE GREATEST(0, (EXTRACT(EPOCH FROM (${command.now.toISOString()}::timestamptz - (
            SELECT min(e.server_ts) FROM session_events e
             WHERE e.session_id = ${command.sessionId}::uuid
               AND e.event_type = ${SessionEventType.CALL_STARTED}::text
          ))) * 1000)::int) END`,
          // The denormalised mirror of the billing row inserted below, written
          // here for the reason T35 writes it on the verdict path: these columns
          // exist for cheap listing queries, and a listing where verdicts show a
          // charge and dropped calls show none would be worse than no column at
          // all. `billing_entries` remains authoritative.
          billCategory: command.billCategory,
          billAmountPaise: command.billAmountPaise,
          version: sql`${sessions.version} + 1`,
          updatedAt: command.now,
        })
        .where(
          and(
            eq(sessions.id, command.sessionId),
            eq(sessions.tenantId, command.tenantId),
            eq(sessions.status, SessionStatus.IN_CALL),
          ),
        )
        .returning({
          id: sessions.id,
          status: sessions.status,
          endedAt: sessions.endedAt,
          talkMs: sessions.talkMs,
          agentId: sessions.agentId,
        });

      if (updated === undefined) return null;

      // Same transaction as the transition. `billing_entries.session_id` is the
      // primary key, so a duplicate is a constraint violation rather than a
      // second charge — and because the UPDATE above already matched exactly
      // once, reaching here twice is not possible for one terminal outcome.
      await tx.execute(sql`
        INSERT INTO billing_entries (session_id, tenant_id, category, amount_paise, billed_at, invoice_month)
        VALUES (
          ${command.sessionId}::uuid,
          ${command.tenantId}::uuid,
          ${command.billCategory}::text,
          ${command.billAmountPaise}::int,
          ${command.now.toISOString()}::timestamptz,
          date_trunc('month', ${command.now.toISOString()}::timestamptz)::date
        )
      `);

      await this.events.append(
        {
          sessionId: command.sessionId,
          tenantId: command.tenantId,
          eventType: command.event.type,
          actorType: command.event.actorType,
          actorId: command.event.actorId,
          payload: command.event.payload,
        },
        tx,
      );

      return {
        id: updated.id,
        status: updated.status as SessionStatus,
        endedAt: updated.endedAt as Date,
        talkMs: updated.talkMs,
        agentId: updated.agentId,
      };
    });
  }

  async submitVerdict(command: SubmitVerdictCommand): Promise<SubmitVerdictOutcome> {
    const at = command.now.toISOString();

    return this.db.transaction(async (tx) => {
      // The single-winner guard (D17), and every predicate earns its place:
      //
      //   - `status = 'IN_CALL'` — the only state a verdict may be submitted
      //     from, and what a customer disconnect will have already changed.
      //   - `agent_id = :agent` — the agent on the call, not merely an agent in
      //     the tenant. Checked here rather than only in the service, so the
      //     window between reading the row and writing it cannot be used.
      //   - `verdict IS NULL` — belt and braces with the status check. §45 names
      //     it explicitly, and it is what makes a replay that somehow reached a
      //     row still `IN_CALL` land on nothing rather than charge twice.
      const [updated] = await tx
        .update(sessions)
        .set({
          status: command.verdict,
          verdict: command.verdict,
          verdictAt: command.now,
          endedAt: command.now,
          // Same derivation as `endCall`, and for the same reason: measured
          // from `CALL_STARTED` rather than from the accept, and null when
          // both parties were never in the room together.
          talkMs: sql`CASE WHEN (
            SELECT min(e.server_ts) FROM session_events e
             WHERE e.session_id = ${command.sessionId}::uuid
               AND e.event_type = ${SessionEventType.CALL_STARTED}::text
          ) IS NULL THEN NULL ELSE GREATEST(0, (EXTRACT(EPOCH FROM (${at}::timestamptz - (
            SELECT min(e.server_ts) FROM session_events e
             WHERE e.session_id = ${command.sessionId}::uuid
               AND e.event_type = ${SessionEventType.CALL_STARTED}::text
          ))) * 1000)::int) END`,
          billCategory: command.billCategory,
          billAmountPaise: command.billAmountPaise,
          // §45. The evidence pipeline (T38) picks the session up from here;
          // setting it inside this transaction is what stops a verdict existing
          // that nothing will ever export.
          exportStatus: 'EXPORTING',
          version: sql`${sessions.version} + 1`,
          updatedAt: command.now,
        })
        .where(
          and(
            eq(sessions.id, command.sessionId),
            eq(sessions.tenantId, command.tenantId),
            eq(sessions.status, SessionStatus.IN_CALL),
            eq(sessions.agentId, command.agentId),
            isNull(sessions.verdict),
          ),
        )
        .returning({
          id: sessions.id,
          status: sessions.status,
          verdict: sessions.verdict,
          billCategory: sessions.billCategory,
          billAmountPaise: sessions.billAmountPaise,
          talkMs: sessions.talkMs,
        });

      // Nothing matched. Rolling back an untouched transaction, and the caller
      // answers 409 (D17).
      if (updated === undefined) return { kind: 'LOST' };

      // The attestation. Written after the transition rather than before, so a
      // checklist can never exist for a verdict that lost the race.
      await this.saveChecklist(tx, command);

      // The AI summary (§19, §20). Only when there was one — see `aiSummary`.
      if (command.aiSummary !== null) await this.saveAiSummary(tx, command.aiSummary);

      // `billing_entries.session_id` is the primary key, so a duplicate is a
      // constraint violation rather than a second charge. Reaching here twice
      // for one session is already impossible — the UPDATE above matched
      // exactly once — and the key is the structural guarantee behind that.
      await tx.execute(sql`
        INSERT INTO billing_entries (session_id, tenant_id, category, amount_paise, billed_at, invoice_month)
        VALUES (
          ${command.sessionId}::uuid,
          ${command.tenantId}::uuid,
          ${command.billCategory}::text,
          ${command.billAmountPaise}::int,
          ${at}::timestamptz,
          date_trunc('month', ${at}::timestamptz)::date
        )
      `);

      for (const event of command.events) {
        await this.events.append(
          {
            sessionId: command.sessionId,
            tenantId: command.tenantId,
            eventType: event.type,
            actorType: event.actorType,
            actorId: event.actorId,
            payload: event.payload,
          },
          tx,
        );
      }

      await this.saveOutbox(tx, command);

      return {
        kind: 'COMMITTED',
        session: {
          id: updated.id,
          status: updated.status as SessionStatus,
          verdict: updated.verdict as string,
          billCategory: updated.billCategory as string,
          billAmountPaise: updated.billAmountPaise as number,
          talkMs: updated.talkMs,
        },
      };
    });
  }

  /**
   * The answers, as one statement.
   *
   * An upsert because the verdict route carries an `Idempotency-Key` and a
   * replay must land on the same rows rather than a primary-key violation.
   * `checked_at` is derived from `checked` here so the table's CHECK constraint
   * cannot be violated by a caller that sent one without the other.
   */
  private async saveChecklist(tx: DbExecutor, command: SubmitVerdictCommand): Promise<void> {
    if (command.checklist.length === 0) return;

    const values = command.checklist.map(
      (item) =>
        sql`(${command.sessionId}::uuid, ${item.key}, ${item.checked}, ${
          item.checked ? sql`${command.now.toISOString()}::timestamptz` : sql`NULL`
        }, ${command.now.toISOString()}::timestamptz)`,
    );

    await tx.execute(sql`
      INSERT INTO session_checklist_items (session_id, item_key, checked, checked_at, updated_at)
      VALUES ${sql.join(values, sql`, `)}
      ON CONFLICT (session_id, item_key) DO UPDATE
         SET checked    = EXCLUDED.checked,
             checked_at = EXCLUDED.checked_at,
             updated_at = EXCLUDED.updated_at
    `);
  }

  /**
   * The AI snapshot (§19, §20).
   *
   * A snapshot, not a stream: the live results went to Redis every couple of
   * seconds during the call, and exactly one row of them becomes durable. This
   * is what keeps PostgreSQL from becoming a telemetry store (D2).
   *
   * `model_versions` is carried because "which model made the call that is
   * being disputed" is the question this row exists to answer months later.
   */
  private async saveAiSummary(tx: DbExecutor, hud: AiHudPayload): Promise<void> {
    await tx.execute(sql`
      INSERT INTO session_ai_summaries (session_id, liveness_score, liveness_status, face_match_score, ocr_status, model_versions)
      VALUES (
        ${hud.session_id}::uuid,
        ${hud.liveness_score}::numeric,
        ${hud.liveness_status}::text,
        ${hud.face_match_score}::numeric,
        ${hud.ocr_status}::text,
        ${JSON.stringify(hud.model_versions)}::jsonb
      )
      ON CONFLICT (session_id) DO UPDATE
         SET liveness_score   = EXCLUDED.liveness_score,
             liveness_status  = EXCLUDED.liveness_status,
             face_match_score = EXCLUDED.face_match_score,
             ocr_status       = EXCLUDED.ocr_status,
             model_versions   = EXCLUDED.model_versions,
             updated_at       = now()
    `);
  }

  /**
   * The transactional outbox row (§27, D21).
   *
   * `INSERT ... SELECT` from `webhook_endpoints` rather than a read followed by
   * an insert: the endpoint is chosen and the row written in one statement, so
   * there is no interval in which an endpoint could be deactivated between the
   * two. A tenant with no active endpoint produces no row and no error — the
   * verification is complete either way, and the enterprise that configured no
   * webhook is not waiting for one.
   *
   * The payload is written without the evidence keys, because they do not exist
   * yet (D21). T42 enriches this same row when the export resolves.
   */
  private async saveOutbox(tx: DbExecutor, command: SubmitVerdictCommand): Promise<void> {
    await tx.execute(sql`
      INSERT INTO webhook_events (tenant_id, session_id, endpoint_id, event_type, payload, status)
      SELECT ${command.tenantId}::uuid,
             ${command.sessionId}::uuid,
             we.id,
             ${command.webhookEventType}::text,
             ${JSON.stringify(command.webhookPayload)}::jsonb,
             'PENDING'
        FROM webhook_endpoints we
       WHERE we.tenant_id = ${command.tenantId}::uuid
         AND we.active = true
    `);
  }

  async findUnrecordedCalls(limit: number): Promise<readonly UnrecordedCallRow[]> {
    if (limit <= 0) return [];

    // Two EXISTS clauses rather than joins: a session qualifies on the presence
    // of one event type and the absence of another, and a join would have to be
    // de-duplicated to say that.
    const rows = await this.db.execute<{
      id: string;
      tenant_id: string;
      room_name: string | null;
    }>(sql`
      SELECT s.id, s.tenant_id, s.room_name
        FROM sessions s
       WHERE s.status = ${SessionStatus.IN_CALL}::text
         AND EXISTS (
           SELECT 1 FROM session_events e
            WHERE e.session_id = s.id
              AND e.event_type = ${SessionEventType.CALL_STARTED}::text
         )
         AND NOT EXISTS (
           SELECT 1 FROM session_events e
            WHERE e.session_id = s.id
              AND e.event_type = ${SessionEventType.EGRESS_STARTED}::text
         )
       ORDER BY s.updated_at
       LIMIT ${limit}::int
    `);

    return rows.map((row) => ({
      id: row.id,
      tenantId: row.tenant_id,
      roomName: row.room_name,
    }));
  }

  async expireOffers(command: ExpireOffersCommand): Promise<readonly ExpiredOfferRow[]> {
    if (command.limit <= 0) return [];

    return this.db.transaction(async (tx) => {
      // `RETURNING` is what makes this safe to run from several API instances
      // at once: each row is taken by exactly one UPDATE, so a second sweeper
      // sees it already `QUEUED` and gets nothing back for it. No advisory
      // lock and no leader election.
      //
      // The subquery bounds the batch — `UPDATE ... LIMIT` is not valid
      // PostgreSQL — and `FOR UPDATE SKIP LOCKED` means two concurrent sweepers
      // take disjoint batches rather than contending for the same rows.
      //
      // `<=` against the same instant the accept compares with `>`: exactly one
      // of the two can match a given row at a given clock reading, so an offer
      // is never both acceptable and expired.
      // A CTE, and the reason is `RETURNING`: it reports the row as it now is,
      // so `RETURNING offered_to_agent_id` on a statement that just set that
      // column to NULL returns NULL for every row. The agent who let the offer
      // lapse would be unreachable, and nothing would ever clear their `BUSY` —
      // the exact bug this sweeper exists to prevent. `due` captures the agent
      // before the update runs, and the final SELECT joins the two so only rows
      // this pass actually took are reported.
      //
      // `FOR UPDATE SKIP LOCKED` in `due` is what lets two sweepers take
      // disjoint batches instead of contending, and the ISO string with an
      // explicit cast is because drizzle's raw template hands parameters to the
      // driver without the column context its query builder has — a Date
      // arrives unserialisable.
      const rows = await tx.execute<{
        id: string;
        tenant_id: string;
        agent_id: string | null;
      }>(sql`
        WITH due AS (
          SELECT id, tenant_id, offered_to_agent_id
            FROM sessions
           WHERE status = ${SessionStatus.OFFERED}::text
             AND offer_expires_at <= ${command.now.toISOString()}::timestamptz
           ORDER BY offer_expires_at
           LIMIT ${command.limit}::int
             FOR UPDATE SKIP LOCKED
        ), swept AS (
          UPDATE sessions s
             SET status = ${SessionStatus.QUEUED}::text,
                 offered_to_agent_id = NULL,
                 offered_at = NULL,
                 offer_expires_at = NULL,
                 version = s.version + 1,
                 updated_at = now()
            FROM due
           WHERE s.id = due.id
          RETURNING s.id
        )
        SELECT due.id, due.tenant_id, due.offered_to_agent_id AS agent_id
          FROM due JOIN swept ON swept.id = due.id
      `);

      const expired = rows.map((row) => ({
        id: String(row.id),
        tenantId: String(row.tenant_id),
        agentId: row.agent_id === null ? null : String(row.agent_id),
      }));

      // One event per swept row, in the same transaction as the sweep. A
      // session that silently reappeared in the queue with nothing explaining
      // why would be exactly the lie the append-only log exists to prevent.
      for (const row of expired) {
        await this.events.append(
          {
            tenantId: row.tenantId,
            sessionId: row.id,
            eventType: command.eventType,
            // The sweeper acts as the system: no agent asked for this, and the
            // agent named below is the one who let it lapse, not the actor.
            actorType: 'SYSTEM',
            actorId: null,
            payload: {
              from: SessionStatus.OFFERED,
              to: SessionStatus.QUEUED,
              agent_id: row.agentId,
            },
          },
          tx,
        );
      }

      return expired;
    });
  }

  async accept(command: AcceptCommand): Promise<SessionAcceptOutcome> {
    return this.db.transaction(async (tx) => {
      const accepted = await tx
        .update(sessions)
        .set({
          status: SessionStatus.IN_CALL,
          agentId: command.agentId,
          // "Accepted at". The moment media actually starts is the LiveKit
          // join webhook's to record (T26); §17.2 puts this here.
          connectedAt: command.now,
          version: sql`${sessions.version} + 1`,
          updatedAt: new Date(),
        })
        .where(
          and(
            eq(sessions.id, command.sessionId),
            eq(sessions.tenantId, command.tenantId),
            eq(sessions.status, SessionStatus.OFFERED),
            // The offer is this agent's. In SQL, so a second agent holding a
            // stale response cannot take a session offered to someone else
            // however the service was reached.
            eq(sessions.offeredToAgentId, command.agentId),
            // And it has not lapsed. Strictly greater, so an offer expiring on
            // this exact millisecond is already gone — the sweeper's predicate
            // is `<=` on the same column and the same clock, so exactly one of
            // the two can match and the boundary belongs to neither twice.
            gt(sessions.offerExpiresAt, command.now),
          ),
        )
        .returning({
          id: sessions.id,
          status: sessions.status,
          agentId: sessions.agentId,
          connectedAt: sessions.connectedAt,
          roomName: sessions.roomName,
          version: sessions.version,
        });

      const row = accepted[0];
      // Zero rows: the sweeper won, another agent's offer, already accepted, or
      // expired. Roll back rather than record an accept that did not happen.
      if (row === undefined) return { kind: 'LOST' } as const;

      // The offer columns are deliberately left as they were. They become
      // history on an `IN_CALL` row — who was offered this, and when — and the
      // sweeper cannot see the row any more because its predicate requires
      // `status = 'OFFERED'`.
      await this.events.append(
        {
          tenantId: command.tenantId,
          sessionId: command.sessionId,
          eventType: command.event.type,
          actorType: command.event.actorType,
          actorId: command.event.actorId,
          payload: command.event.payload,
        },
        tx,
      );

      return {
        kind: 'ACCEPTED',
        session: {
          id: row.id,
          status: row.status as SessionStatus,
          /* c8 ignore next 2 -- both were just set by this statement */
          agentId: row.agentId ?? command.agentId,
          connectedAt: row.connectedAt ?? command.now,
          roomName: row.roomName,
          version: row.version,
        },
      } as const;
    });
  }

  async claim(command: ClaimCommand): Promise<SessionClaimOutcome> {
    return this.db.transaction(async (tx) => {
      // 1. Serialise this agent against their own concurrent claims.
      //
      // Without this the capacity check below is a time-of-check/time-of-use
      // hole, and not a theoretical one: READ COMMITTED gives each statement a
      // fresh snapshot, two claims for the same agent touch *different*
      // session rows so they never block each other, and neither sees the
      // other's uncommitted OFFERED. Both would count zero and both would
      // commit. Locking the agent's own `users` row makes concurrent claims by
      // one agent take turns, and costs nothing to anyone else: two agents
      // racing for one session lock different rows here and are still decided
      // by the conditional UPDATE.
      //
      // No deadlock is possible from this ordering — an agent locks exactly one
      // row, always their own, before touching any session.
      await tx
        .select({ id: users.id })
        .from(users)
        .where(and(eq(users.id, command.agentId), eq(users.tenantId, command.tenantId)))
        .for('update');

      // 2. Count what this agent is already holding (R5), using the same
      //    predicate the availability guard uses.
      const [counted] = await tx
        .select({ active: sql<string>`count(*)` })
        .from(sessions)
        .where(holdsActiveWork(command.tenantId, command.agentId));

      const active = Number(counted?.active ?? 0);
      if (active >= command.maxConcurrent) {
        // Nothing was written, and the rollback releases the agent lock.
        return { kind: 'AT_CAPACITY', active } as const;
      }

      // 3. The claim itself, exactly as D5 specifies it.
      //
      // Three predicates and no fourth: id, tenant, and `status = 'QUEUED'`.
      // Not the caller's observed version — the session being queued is the
      // whole precondition, and a version predicate would lose a legitimate
      // claim to any unrelated write that had bumped it.
      const claimed = await tx
        .update(sessions)
        .set({
          status: SessionStatus.OFFERED,
          offeredToAgentId: command.agentId,
          offeredAt: command.offeredAt,
          offerExpiresAt: command.offerExpiresAt,
          version: sql`${sessions.version} + 1`,
          updatedAt: new Date(),
        })
        .where(
          and(
            eq(sessions.id, command.sessionId),
            eq(sessions.tenantId, command.tenantId),
            eq(sessions.status, SessionStatus.QUEUED),
          ),
        )
        .returning({
          id: sessions.id,
          status: sessions.status,
          offeredToAgentId: sessions.offeredToAgentId,
          offeredAt: sessions.offeredAt,
          offerExpiresAt: sessions.offerExpiresAt,
          version: sessions.version,
        });

      const row = claimed[0];
      // Zero rows: another agent won, or the session left the queue between
      // the read and the write. Roll back, so no event records an offer that
      // did not happen.
      if (row === undefined) return { kind: 'LOST' } as const;

      await this.events.append(
        {
          tenantId: command.tenantId,
          sessionId: command.sessionId,
          eventType: command.event.type,
          actorType: command.event.actorType,
          actorId: command.event.actorId,
          payload: command.event.payload,
        },
        tx,
      );

      return {
        kind: 'CLAIMED',
        session: {
          id: row.id,
          status: row.status as SessionStatus,
          /* c8 ignore next 3 -- all three were just set by this statement */
          offeredToAgentId: row.offeredToAgentId ?? command.agentId,
          offeredAt: row.offeredAt ?? command.offeredAt,
          offerExpiresAt: row.offerExpiresAt ?? command.offerExpiresAt,
          version: row.version,
        },
      } as const;
    });
  }
}
