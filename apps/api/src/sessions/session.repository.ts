/**
 * Session persistence.
 *
 * PostgreSQL is authoritative for session state (D1, invariant I1). Every
 * mutation here is a **guarded** update: the caller says which status and
 * version it observed, and the UPDATE only commits if the row still looks that
 * way. Zero affected rows means someone else moved the session first, and the
 * caller turns that into a `409`.
 *
 * That is the single-winner pattern D5 and D17 specify, applied to the customer
 * side of the lifecycle. It is not optimistic locking bolted on for tidiness:
 * a customer pressing "abort" while an agent submits a verdict is a real race,
 * and only one of them may commit.
 *
 * Each mutation writes its `session_events` row **inside the same transaction**
 * as the update. A status change with no event, or an event for a change that
 * did not commit, would both be lies in the audit trail.
 *
 * Port plus adapter, as with `ApiKeyStore` (T09) and `TenantConfigStore`: the
 * service depends on the interface, so the lifecycle rules are testable without
 * a database, and the SQL lives in exactly one file.
 */

